"""benchmark.json -> reports/benchmark.md"""
from __future__ import annotations


def _fmt(v, nd=1):
    if v is None:
        return "–"
    if isinstance(v, float):
        return f"{v:.{nd}f}"
    return str(v)


def _gate(ok):
    return "PASS" if ok else "FAIL"


def render_markdown(res: dict) -> str:
    L = []
    L.append("# Benchmark report (auto-generated by `python -m bench.run_benchmark`)\n")
    L.append(f"Generated {res['generated_at']}.\n")
    L.append("> **Ground truth disclosure.** No tape or laser measurements exist for these captures: the author "
             "had no iPhone or site access, and worked only from the supplied sample data (three StrayScanner "
             "LiDAR captures of one apartment). Every gate that needs tape ground truth is scored here against "
             "the strongest available **proxy** and labelled as such. To score against real measurements, fill "
             "`bench/ground_truth/<capture>.yaml` and re-run.\n")
    L.append("## Captures\n")
    L.append("| capture | description | lidar | video | photo |\n|---|---|---|---|---|")
    for c, d in res["captures"].items():
        o = res["outputs"]
        L.append(f"| `{c}` | {d['desc']} | {'yes' if o.get(c + '/lidar') else 'no'} | "
                 f"{'yes' if o.get(c + '/video') else 'no'} | {'yes' if o.get(c + '/photo') else 'no'} |")
    L.append("")

    L.append("## Gates\n")
    L.append("| gate | spec | tier | measured (proxy) | status |\n|---|---|---|---|---|")
    for key, r in res.get("repeatability", {}).items():
        w = r["walls"]
        tier = key.split("/")[-1]
        if w.get("n"):
            L.append(f"| Repeatability | two captures agree within 1 cm or 0.5% per wall | {tier} | "
                     f"{w['pass_rate'] * 100:.0f}% of {w['n']} matched walls pass (median diff {w['median_abs_mm']} mm); "
                     f"rooms matched {len(r['rooms'])}/{max(r['rooms_a'], r['rooms_b'])} | "
                     f"{_gate(w['pass_rate'] >= 0.999)} |")
        o = r["openings"]
        if o.get("score") is not None:
            L.append(f"| Opening widths (proxy: capture-vs-capture) | ≤ 2 cm on ≥ 85% incl. missed/phantom | {tier} | "
                     f"{o['within_2cm']}/{max(o['openings_a'], o['openings_b'])} = {o['score'] * 100:.0f}% "
                     f"(matched {o['matched']}, median diff {_fmt(o['median_abs_mm'])} mm) | {_gate(o['score'] >= 0.85)} |")
    sh = res.get("ceiling_split_half")
    if sh:
        sp = [r["spread_mm"] for r in sh["rooms"] if r["spread_mm"] is not None]
        if sp:
            ok = all(s <= 10 for s in sp)
            L.append(f"| Ceiling height spread (proxy: split-half of one capture) | ≤ 1 cm | lidar | "
                     f"max {max(sp):.1f} mm over {len(sp)} rooms | {_gate(ok)} (proxy) |")
    L.append("| Ceiling height vs tape | ≤ 1.5 cm per room | all | not evaluable: no tape ground truth | N/A |")
    for key, d in (res.get("drift_ablation") or {}).items():
        if d:
            L.append(f"| Drift accountability | ablation on/off | {key} | footprint {d['footprint_on']:.2f} m² on vs "
                     f"{d['footprint_off']:.2f} m² off; wall-plane spread {d['wall_plane_spread_mm'][0]} → "
                     f"{d['wall_plane_spread_mm'][1]} mm | reported |")
    for key, a in res.get("tier_vs_lidar", {}).items():
        tier = key.split("/")[-1]
        w = a["walls"]
        tol = "±3%" if tier == "video" else "±8%"
        if w.get("n"):
            L.append(f"| {tier} wall lengths (proxy: vs LiDAR tier) | {tol} | {tier} ({key.split('/')[0]}) | "
                     f"{w['pass_rate'] * 100:.0f}% of {w['n']} walls within {tol}; median {w['median_abs_pct']}%; "
                     f"CI95 coverage {w['ci95_coverage'] * 100:.0f}% | {_gate(w['pass_rate'] >= 0.85)} |")
        L.append(f"| {tier} footprint (proxy: vs LiDAR tier) | ±8% (photo) | {tier} ({key.split('/')[0]}) | "
                 f"{a['footprint_err_pct']:+.1f}%, inside own CI95: {a['footprint_in_ci95']}; rooms {a['rooms_a']} vs {a['rooms_b']} | "
                 f"{_gate(abs(a['footprint_err_pct']) <= 8) if tier == 'photo' else 'reported'} |")
    L.append("| Head-to-head vs consumer app | beat/tie ≥ 70% of dims | lidar | not run: no access to an iPhone to "
             "produce a magicplan/Polycam export of the same rooms | BLOCKED |")
    L.append("")

    L.append("## Repeatability detail\n")
    for key, r in res.get("repeatability", {}).items():
        L.append(f"### {key}\n")
        L.append(f"Registration: {r['registration']}  \nRoom matches (IoU): " +
                 ", ".join(f"{m['a']}↔{m['b']} ({m['iou']:.2f}, {m['area_a']:.2f} vs {m['area_b']:.2f} m²)" for m in r["rooms"]))
        L.append("\n| wall A | wall B | A (m) | B (m) | diff (mm) | pass |\n|---|---|---|---|---|---|")
        for w in r["wall_pairs"]:
            e = abs(w["diff"])
            ok = e <= 0.01 or e <= 0.005 * w["len_b"]
            L.append(f"| {w['wall_a']} | {w['wall_b']} | {w['len_a']:.3f} | {w['len_b']:.3f} | {w['diff'] * 1000:+.1f} | {'✓' if ok else '✗'} |")
        L.append("")

    if res.get("ceilings"):
        L.append("## Ceiling heights (LiDAR tier)\n")
        L.append("| capture | room | observed | value (m) | 95% CI |\n|---|---|---|---|---|")
        for key, rows in res["ceilings"].items():
            for r in rows:
                L.append(f"| {key} | {r['room']} {r['name']} | {r['observed']} | {r['value']:.3f} | "
                         f"{r['ci95'][0]:.3f}–{r['ci95'][1]:.3f} |")
        L.append("")
    if sh:
        L.append("## Ceiling split-half (proxy)\n")
        L.append(sh["method"] + "\n")
        L.append("| room | full | half 1 | half 2 | spread (mm) |\n|---|---|---|---|---|")
        for r in sh["rooms"]:
            L.append(f"| {r['room']} {r['name']} | {_fmt(r['full'], 3)} | {_fmt(r['half1'], 3)} | {_fmt(r['half2'], 3)} | {_fmt(r['spread_mm'])} |")
        L.append("")
    if res.get("timing_s"):
        L.append("## Timing (seconds, Apple M4 Pro, one command per capture)\n")
        L.append("| capture/tier | seconds |\n|---|---|")
        for k, v in res["timing_s"].items():
            L.append(f"| {k} | {v} |")
        L.append("")
    return "\n".join(L) + "\n"
